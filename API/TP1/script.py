notes = []
for id in ids:
    url = f'https://api.themoviedb.org/3/movie/{id}?api_key={SECRET_KEY}'
    response = requests.get(url)
    if response.status_code == 200:
        data = response.json()
        movie = {
            "original_title": data.get("original_title"),
            "vote_average": data.get("vote_average")
        }
        notes.append(movie)
    else:
        print(f"Erreur pour l'ID {id} : {response.status_code}") 

notes.sort(key=lambda x: x["vote_average"], reverse=True)
